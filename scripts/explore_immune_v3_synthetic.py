"""Bounded A0-A4 synthetic optimization diagnostic, never a downstream score.

After activating pllm, local check:
python scripts/explore_immune_v3_synthetic.py --ablation A4 --cpu-test --steps 2 --output-dir /tmp/v3-new
GPU: use the YAMLs generated by scripts/prepare_immune_v3_exploration.py.
"""
import argparse
from contextlib import nullcontext
from dataclasses import asdict
import hashlib
import json
from pathlib import Path
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import torch
from dllm.pipelines.immune_llada.data.records import BioSeqChain, BioSeqRecord
from dllm.pipelines.immune_llada.v3.layout import ImmuneCollator
from dllm.pipelines.immune_llada.v3.model import ImmuneConfig, ImmuneModel
from dllm.pipelines.llada.models.configuration_llada import ActivationCheckpointingStrategy
from scripts.profile_immune_v3 import code_hashes, verify_memory_profile
from scripts.smoke_immune_v3_cpu import measure


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ablation', choices=['A0', 'A1', 'A2', 'A3', 'A4'], required=True)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--profile-dir', type=Path)
    parser.add_argument('--batch-size', type=int, default=1)
    parser.add_argument('--grad-accum', type=int, default=1)
    parser.add_argument('--steps', type=int, default=20)
    parser.add_argument('--cpu-test', action='store_true')
    args = parser.parse_args()
    if not 1 <= args.steps <= 100 or min(args.batch_size, args.grad_accum) < 1:
        raise ValueError('Positive batches and 1-100 optimizer steps required')
    torch.set_num_threads(2 if args.cpu_test else 4)
    torch.manual_seed(42)
    fingerprints = code_hashes()
    config = ImmuneConfig(ablation=args.ablation)
    if args.cpu_test:
        if args.batch_size != 1 or args.grad_accum != 1 or args.steps > 5:
            raise ValueError('Local plumbing test is restricted to batch 1, accumulation 1, <=5 steps')
        config = ImmuneConfig(ablation=args.ablation, d_model=64, n_layers=2, n_heads=4,
                              mlp_hidden_size=128, max_length=512, full_capacity=24, fragment_capacity=16)
        device = 'cpu'
    else:
        if args.profile_dir is None or args.batch_size * args.grad_accum != 256:
            raise ValueError('GPU suite requires a measured profile and global batch 256')
        measured = verify_memory_profile(args.profile_dir, args.ablation, args.batch_size)
        if measured['config'] != asdict(config):
            raise ValueError('Profile configuration differs')
        if not torch.cuda.is_available() or torch.cuda.get_device_name() != measured['gpu']:
            raise ValueError('GPU must match the recorded memory profile')
        device = 'cuda'
    args.output_dir.mkdir(parents=True, exist_ok=False)
    model = ImmuneModel(config).to(device)
    model.backbone.set_activation_checkpointing(ActivationCheckpointingStrategy.whole_layer)
    # One fixed artificial pair: evaluates optimization wiring, not generalization.
    rows = [BioSeqRecord([BioSeqChain('CAAAAAAF', 'tcr_beta'), BioSeqChain('CGGGW', 'tcr_alpha')],
                         'tcr', 'synthetic_optimization_only')]
    collator = ImmuneCollator(args.ablation, max_length=config.max_length,
                             full_capacity=config.full_capacity, fragment_capacity=config.fragment_capacity)
    batch = {k: v.to(device) for k, v in collator(rows * args.batch_size).items()}
    evaluation = {k: v.to(device) for k, v in collator(rows).items()}
    optimizer = torch.optim.AdamW(model.parameters(), lr=1e-4)
    def precision():
        return torch.autocast('cuda', dtype=torch.bfloat16) if device == 'cuda' else nullcontext()
    def evaluate():
        with precision():
            return measure(model, evaluation)
    if device == 'cuda':
        torch.cuda.reset_peak_memory_stats()
    start = time.monotonic()
    report = dict(kind='synthetic_optimization_diagnostic', status='running', biological_quality_claim=False,
                  cpu_test=args.cpu_test, config=asdict(config), seed=42, steps=args.steps,
                  micro_batch=args.batch_size, grad_accum=args.grad_accum,
                  global_batch=args.batch_size * args.grad_accum, learning_rate=1e-4,
                  scheduler='constant; diagnostic only', actual_length=batch['input_ids'].shape[1],
                  parameters=sum(p.numel() for p in model.parameters()), source_sha256=fingerprints,
                  diagnostic_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                  metric_helper_sha256=hashlib.sha256((ROOT/'scripts/smoke_immune_v3_cpu.py').read_bytes()).hexdigest(),
                  initial=evaluate(), trace=[])
    def write_report():
        (args.output_dir/'summary.json').write_text(json.dumps(report, indent=2, allow_nan=False)+'\n')
    write_report()
    for step in range(1, args.steps + 1):
        model.train()
        optimizer.zero_grad(set_to_none=True)
        level = (.25, .5, .75, 1.)[(step-1) % 4]
        for _ in range(args.grad_accum):
            with precision():
                result = model(**batch, token_t=torch.full_like(batch['input_ids'], level, dtype=torch.float))
                loss = result['loss'] / args.grad_accum
            if not torch.isfinite(loss):
                raise FloatingPointError(f'Nonfinite loss at step {step}')
            loss.backward()
        norm = torch.nn.utils.clip_grad_norm_(model.parameters(), 1., error_if_nonfinite=True)
        optimizer.step()
        if step % 5 == 0 or step == args.steps:
            report['trace'].append(dict(step=step, gradient_norm=float(norm), **evaluate()))
            write_report()
            print(json.dumps(report['trace'][-1]), flush=True)
    if code_hashes() != fingerprints:
        raise RuntimeError('Production code changed during diagnostic')
    report.update(status='completed', final=evaluate(), elapsed_seconds=time.monotonic()-start)
    report['loss_decreased'] = report['final']['loss'] < report['initial']['loss']
    report['max_allocated_gib'] = torch.cuda.max_memory_allocated()/2**30 if device == 'cuda' else None
    write_report()
    (args.output_dir/'COMPLETE.json').write_text(json.dumps(dict(status='completed',
        kind=report['kind'], biological_quality_claim=False, loss_decreased=report['loss_decreased']))+'\n')
    print(json.dumps(dict(output_dir=str(args.output_dir), loss_decreased=report['loss_decreased'])), flush=True)


if __name__ == '__main__':
    main()
